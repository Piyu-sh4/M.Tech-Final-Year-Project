const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium, webkit } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core');
const { base, chromiumOptions } = require('./support/browser-target.cjs');

(async () => {
  const browser = process.env.ENGINE === 'webkit' ? await webkit.launch() : await chromium.launch({
    ...chromiumOptions,
  });
  try {
    const page = await browser.newPage({viewport:{width:Number(process.env.WFI_WIDTH || 390),height:850}});
    await page.goto(base+'/login.html');
    await page.locator('#email').fill('admin@wip.com');
    await page.locator('#password').fill('P123/');
    await page.locator('#loginBtn').click();
    await page.waitForURL('**/admin-dashboard.html');
    const marker = 'Review workflow '+Date.now();
    await page.goto(base+'/meetings.html');
    await page.getByRole('button',{name:'Schedule meeting',exact:true}).click();
    const form = page.locator('#record-form');
    await form.getByLabel('Title',{exact:true}).fill(marker);
    await form.getByLabel('Date and time').fill('2027-12-05T10:30');
    await form.getByLabel('Duration in minutes').fill('30');
    await form.getByLabel('Agenda').fill('Review test');
    await form.getByLabel('Meeting provider').selectOption('zoom');
    await form.getByLabel('Meeting link').fill('https://zoom.us/j/123456789');
    const invitees = form.getByLabel('Invite colleagues (optional)');
    await invitees.selectOption({index:0});
    await form.getByRole('button',{name:'Save',exact:true}).click();
    await form.waitFor({state:'hidden'});
    await page.getByLabel('Search records').fill(marker);
    const meeting = page.getByRole('row').filter({hasText:marker});
    await meeting.getByText('Meeting actions',{exact:true}).click();
    await meeting.getByRole('button',{name:'Reschedule meeting',exact:true}).click();
    await form.getByLabel('New date and time').fill('2027-12-06T10:30');
    await form.getByRole('button',{name:'Reschedule meeting',exact:true}).click();
    await form.waitFor({state:'hidden'});
    await meeting.getByText('Meeting actions',{exact:true}).click();
    await meeting.getByRole('button',{name:'Cancel meeting',exact:true}).click();
    await form.getByLabel('Cancellation reason').selectOption('Scheduling conflict');
    await form.getByRole('button',{name:'Cancel meeting',exact:true}).click();
    await form.waitFor({state:'hidden'});
    await meeting.filter({hasText:'Scheduling conflict'}).waitFor();
    const download = page.waitForEvent('download');
    await meeting.getByRole('button',{name:'Download record PDF'}).click();
    assert.equal(fs.readFileSync(await (await download).path()).subarray(0,5).toString(),'%PDF-');
    const wordDownload = page.waitForEvent('download');
    await meeting.getByRole('button', { name: 'Download record Word document' }).click();
    const word = await wordDownload;
    assert.equal(word.suggestedFilename(), 'meetings-record.docx');
    const extracted = await require('mammoth').extractRawText({ buffer: fs.readFileSync(await word.path()) });
    assert.ok(extracted.value.includes(marker) && extracted.value.includes('Scheduling conflict'));
    await page.goto(base+'/notifications.html');
    await page.getByText('Meeting cancelled: '+marker+' · Scheduling conflict',{exact:true}).waitFor();
    const task = await page.evaluate(async title => {
      const response = await fetch('/api/tasks',{method:'POST',headers:{Authorization:'Bearer '+localStorage.getItem('token'),'Content-Type':'application/json'},body:JSON.stringify({title})});
      return response.json();
    },marker);
    await page.goto(base+'/tasks.html');
    const taskRow=page.getByRole('row').filter({hasText:marker});
    await taskRow.getByText('Task actions',{exact:true}).click();
    await taskRow.getByRole('button',{name:'Edit details',exact:true}).click();
    const editor = page.getByRole('dialog',{name:'Edit task'});
    await editor.getByLabel('Title',{exact:true}).fill(marker+' edited');
    await editor.getByRole('button',{name:'Save task',exact:true}).click();
    await editor.waitFor({state:'hidden'});
    await page.reload();
    await page.getByRole('textbox', { name: 'Search tasks' }).fill(marker);
    await page.locator('#task-progress-summary').filter({ hasText: '0 of 1 matching tasks completed.' }).waitFor();
    const edited = page.getByRole('row').filter({hasText:marker+' edited'});
    await edited.getByText('Task actions',{exact:true}).click();
    const taskDownload = page.waitForEvent('download');
    await edited.getByRole('button',{name:'Download PDF',exact:true}).click();
    assert.equal((await taskDownload).suggestedFilename(),'task-'+task.task_id+'.pdf');
    await page.goto(base+'/reports.html');
    const reportDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download report PDF' }).first().click();
    const report = await reportDownload;
    assert.match(report.suggestedFilename(), /^reports-\d+\.pdf$/);
    assert.equal(fs.readFileSync(await report.path()).subarray(0, 5).toString(), '%PDF-');
    const employee = await browser.newPage({viewport:{width:Number(process.env.WFI_WIDTH || 390),height:850}});
    await employee.goto(base + '/login.html');
    await employee.getByLabel('Email address').fill('employee@wfintelligence.com');
    await employee.getByLabel('Password', { exact: true }).fill('P123/');
    await employee.getByRole('button', { name: 'Sign in', exact: true }).click();
    await employee.waitForURL('**/employee-dashboard.html');
    await employee.goto(base + '/helpdesk.html');
    await employee.getByRole('button', { name: /New Ticket/ }).first().click();
    await employee.getByRole('button', { name: /IT Hardware/ }).click();
    await employee.locator('#ntStep1').getByRole('button', { name: /Next/ }).click();
    await employee.getByLabel('Subject').fill(marker);
    await employee.getByLabel('Detailed Description').fill('A seeded browser workflow checks the requester can close this ticket.');
    await employee.locator('#ntStep2').getByRole('button', { name: /Next/ }).click();
    await employee.getByRole('button', { name: /Submit Ticket/ }).click();
    const ticket = employee.locator('.ticket-card').filter({ hasText: marker });
    await ticket.getByRole('button', { name: 'View ticket' }).click();
    employee.once('dialog', dialog => dialog.accept());
    await employee.getByRole('button', { name: 'Close my ticket' }).click();
    await ticket.getByText('CLOSED', { exact: true }).waitFor();
    await employee.reload();
    await ticket.getByText('CLOSED', { exact: true }).waitFor();
    console.log('PASS meeting links, invitees, rescheduling, cancellation, notifications, record and report PDFs, task edit/filter/chart, and ticket closure');
  } finally {
    await browser.close();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
